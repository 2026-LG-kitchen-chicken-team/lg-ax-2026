// Inline the office build (vite build --mode office) into one HTML file: web/prototypes/agent-office/factory.html.
// office.py install copies it next to the observer's records (runtime-data/agent-office/), where it reads live.js.
import {readFileSync,writeFileSync,readdirSync,existsSync} from 'node:fs';
import {execSync} from 'node:child_process';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const here=dirname(fileURLToPath(import.meta.url)),app=join(here,'..'),dist=join(app,'dist-office');
const target=join(dist,'factory.html');
let html=readFileSync(join(dist,'index.html'),'utf8');
const files=readdirSync(join(dist,'assets')),js=files.filter(f=>f.endsWith('.js')),css=files.filter(f=>f.endsWith('.css'));
if(js.length!==1||css.length!==1||files.length!==2)throw new Error(`expected one js and one css asset, got ${files.join(', ')}`);
const code=readFileSync(join(dist,'assets',js[0]),'utf8'),style=readFileSync(join(dist,'assets',css[0]),'utf8');
if(/<\/script/i.test(code)||/<\/style/i.test(style))throw new Error('bundle contains a closing script/style tag');
const scriptTag=new RegExp(`<script type="module" crossorigin src="\\./assets/${js[0].replace('.','\\.')}"></script>`);
const linkTag=new RegExp(`<link rel="stylesheet" crossorigin href="\\./assets/${css[0].replace('.','\\.')}">`);
if(!scriptTag.test(html)||!linkTag.test(html))throw new Error('asset tags not found in dist-office/index.html');
html=html.replace(linkTag,()=>`<style>\n${style}\n</style>`).replace(scriptTag,()=>'').replace('</body>',()=>`<script type="module">\n${code}\n</script>\n</body>`);
if(/<script[^>]+src=/i.test(html))throw new Error('external script left in the page');
const banner='<!-- Built from web/prototypes/control-room/factory-dashboard (npm run build:office). Edit the factory sources, not this file. -->\n';
html=html.replace(/\r+\n/g,'\n').replace(/^<!doctype html>\n?/i,()=>'<!doctype html>\n'+banner);
function notices(){
  const paths=execSync('npm ls --omit=dev --all --parseable',{cwd:app,encoding:'utf8'}).split(/\r?\n/).filter(Boolean).slice(1),byText=new Map();
  for(const dir of new Set(paths)){
    const pkgFile=join(dir,'package.json');if(!existsSync(pkgFile))continue;
    const pkg=JSON.parse(readFileSync(pkgFile,'utf8')),lic=readdirSync(dir).find(f=>/^(licen[cs]e|copying)(\.|$)/i.test(f));
    const text=lic?readFileSync(join(dir,lic),'utf8').replace(/\r\n/g,'\n').trim():`License: ${pkg.license||'see package'}`;
    byText.set(text,[...(byText.get(text)||[]),`${pkg.name}@${pkg.version}`]);
  }
  const parts=['THIRD-PARTY NOTICES (generated by scripts/publish-office.mjs)',...[...byText].sort((a,b)=>a[1][0].localeCompare(b[1][0])).map(([text,pkgs])=>`${pkgs.sort().join(', ')}\n\n${text}`)];
  return '<!--\n'+parts.join('\n\n----------------------------------------\n\n').replace(/-->/g,'-- >')+'\n-->\n';
}
html=html.replace(/<\/html>\s*$/i,()=>'</html>\n'+notices());
writeFileSync(target,html,'utf8');
console.log(`wrote ${target} (${(Buffer.byteLength(html)/1024).toFixed(0)} KB)`);
